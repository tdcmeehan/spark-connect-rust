LAMBDA = "|xs: Vec<Column>| xs.into_iter().last().unwrap()"


def split_params(params):
    parts, current, depth = [], "", 0
    for char in params:
        if char in "<(":
            depth += 1
        elif char in ">)":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(current)
            current = ""
            continue
        current += char
    if current.strip():
        parts.append(current)
    return [part.split(":", 1)[1].strip() for part in parts]


def argument(param_type, index):
    if param_type == "Column":
        return f'col("c{index}")'
    if param_type.startswith("impl IntoIterator<Item ="):
        return f'[col("c{index}a"), col("c{index}b")]'
    if param_type == "&str":
        return f'"s{index}"'
    if param_type == "Vec<u8>":
        return "vec![1u8, 2]"
    if param_type == "bool":
        return "true"
    if param_type == "i32":
        return "256"
    if param_type in ("F", "G"):
        return LAMBDA
    return None


def generate(source):
    pattern = re.compile(
        r"^pub fn ([A-Za-z0-9_#]+)(?:<[^(]*>)?\(([^{]*?)\)\s*->\s*Column\b", re.M | re.S
    )
    cases, skipped = [], []
    for match in pattern.finditer(source):
        name, params = match.group(1), match.group(2)
        args = [argument(t, i) for i, t in enumerate(split_params(params))]
        if any(a is None for a in args):
            skipped.append(name)
            continue
        label = name.removeprefix("r#")
        call = f"f::{name}({', '.join(args)})"
        cases.append(f'        "functions::{label}" => |c| {{ c.column(&{call}); Ok(()) }},')
    body = "\n".join(cases)
    text = (
        f"{LICENSE}\n"
        "// Generated by scripts/gen_request_snapshot_functions.py. Do not edit.\n"
        "\n"
        "use spark_connect::column::Column;\n"
        "use spark_connect::functions::{self as f, col};\n"
        "\n"
        "use crate::Case;\n"
        "\n"
        "pub fn cases() -> Vec<Case> {\n"
        "    cases![\n"
        f"{body}\n"
        "    ]\n"
        "}\n"
    )
    return text, skipped


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--functions", default=FUNCTIONS_RS)
    parser.add_argument("--output", default=OUTPUT)
    args = parser.parse_args(argv)
    text, skipped = generate(Path(args.functions).read_text())
    Path(args.output).write_text(text)
    if skipped:
        print("not generated: " + ", ".join(skipped), file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1:])
