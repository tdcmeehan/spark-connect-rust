"""Generate one request-snapshot case per public SQL function of the Rust API.

Reads the `pub fn` items of the functions module and writes
crates/spark-connect/tests/request_snapshots/cases/functions_generated.rs, where each
case calls its function with a distinct argument per parameter and records the
resulting column. Functions with a parameter type the generator cannot fill are
listed on stderr and get a hand-written case in cases/functions.rs.
"""

